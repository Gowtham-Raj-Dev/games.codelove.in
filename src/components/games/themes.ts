import type { CSSProperties } from "react";

/**
 * Each game's own visual identity for its UI: panel material, button shape, HUD chips, title
 * effect. The shared UI (src/components/games/shared/ui.tsx) and each game's HUD use the `g-*`
 * classes from globals.css, which read these variables — so the same components look completely
 * different per game. Fonts are separate (src/lib/game-fonts.ts → --game-display / --game-body).
 */
export interface GameTheme {
  /** Panels (menus, modals, how-to-play). */
  panel: string;
  panelText: string;
  panelMuted: string;
  panelBorder: string;
  panelRadius: string;
  panelShadow: string;
  panelBlur?: string;
  /** Primary button. */
  button: string;
  buttonText: string;
  buttonBorder: string;
  buttonRadius: string;
  buttonShadow: string;
  buttonShadowPressed: string;
  buttonTextShadow?: string;
  /** Slants buttons (racing style), e.g. "-12deg". */
  skew?: string;
  /** Secondary button. */
  soft: string;
  softText: string;
  softBorder: string;
  /** HUD chips and icon buttons over the 3D view. */
  hud: string;
  hudText: string;
  hudBorder: string;
  hudRadius: string;
  /** Big game titles. */
  title: string;
  titleAccent: string;
  titleShadow: string;
  uppercase: boolean;
  italic: boolean;
  tracking: string;
  /** Keyboard key chips. */
  kbd: string;
  kbdText: string;
  kbdBorder: string;
  /** Loading screen background and text. */
  loadingBg: string;
  loadingText: string;
  /** Face for buttons, labels and numbers (default: the display face). */
  uiFont?: "display" | "body";
}

